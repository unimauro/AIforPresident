const PDFGenerator = {
  // Map emojis to simple text labels for PDF (Helvetica doesn't support emojis)
  iconMap: {
    '📚': '[EDU]', '🏥': '[SAL]', '💼': '[ECO]', '🛡️': '[SEG]',
    '⚖️': '[JUS]', '🌿': '[AMB]', '🚀': '[TEC]', '🤝': '[SOC]',
    '🔬': '[CIE]', '🔒': '[COR]', '💰': '[FIN]', '🏛️': '[GOB]',
    '⚠️': '[!]', '🗳️': '[VOT]', '📊': '[EST]', '📈': '[+]',
    '🎤': '[MIC]', '📋': '[DOC]', '🔴': '[*]', '📺': '[TV]'
  },

  sanitizeIcon(text) {
    let result = text;
    for (const [emoji, label] of Object.entries(this.iconMap)) {
      result = result.replaceAll(emoji, label);
    }
    // Remove any remaining emojis (surrogate pairs and variation selectors)
    result = result.replace(/[\u{1F000}-\u{1FFFF}]|[\u{2600}-\u{27BF}]|[\u{FE00}-\u{FE0F}]|[\u{200D}]/gu, '');
    return result;
  },

  async generate() {
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF('p', 'mm', 'a4');
    const isEn = I18n.locale === 'en';
    const pageWidth = 210;
    const margin = 20;
    const contentWidth = pageWidth - margin * 2;
    let y = 20;

    // Load data from current dashboard path
    const base = Dashboard.basePath;
    const [proposals, stats, candidates, issues] = await Promise.all([
      fetch(`${base}proposals.json`).then(r => r.json()),
      fetch(`${base}statistics.json`).then(r => r.json()),
      fetch(`${base}candidates.json`).then(r => r.json()).catch(() => []),
      fetch(`${base}issues.json`).then(r => r.json())
    ]);

    // Colors
    const blue = [88, 166, 255];
    const dark = [13, 17, 23];
    const gray = [139, 148, 158];
    const white = [230, 237, 243];
    const green = [63, 185, 80];
    const gold = [210, 153, 34];
    const red = [248, 81, 73];

    // === COVER PAGE ===
    doc.setFillColor(...dark);
    doc.rect(0, 0, pageWidth, 297, 'F');

    // Title
    doc.setTextColor(...blue);
    doc.setFontSize(32);
    doc.setFont('helvetica', 'bold');
    doc.text('AI for President', pageWidth / 2, 60, { align: 'center' });

    const countryInfo = Dashboard.countryInfo[Dashboard.countryCode] || Dashboard.countryInfo.PE;
    const countryName = isEn ? countryInfo.name_en : countryInfo.name;

    doc.setFontSize(24);
    doc.setTextColor(...white);
    doc.text(countryName, pageWidth / 2, 80, { align: 'center' });

    // Subtitle
    doc.setFontSize(14);
    doc.setTextColor(...gray);
    doc.text(
      isEn ? 'Ideal governance proposals generated by AI' : 'Propuestas de gobernanza ideal generadas por IA',
      pageWidth / 2, 95, { align: 'center' }
    );

    doc.text(
      isEn ? '2026 Election Analysis' : 'Análisis Electoral 2026',
      pageWidth / 2, 105, { align: 'center' }
    );

    // Decorative line
    doc.setDrawColor(...blue);
    doc.setLineWidth(1);
    doc.line(60, 115, 150, 115);

    // Stats on cover
    y = 135;
    doc.setFontSize(10);
    doc.setTextColor(...gray);
    const statKeys = ['population', 'gdp_per_capita', 'poverty_rate', 'literacy_rate', 'life_expectancy', 'unemployment'];
    const statsArr = statKeys.map(k => stats[k]);

    for (let i = 0; i < statsArr.length; i += 3) {
      const row = statsArr.slice(i, i + 3);
      row.forEach((s, j) => {
        const x = margin + j * (contentWidth / 3) + (contentWidth / 6);
        doc.setFontSize(18);
        doc.setTextColor(...blue);
        doc.setFont('helvetica', 'bold');
        doc.text(this.formatStatValue(s), x, y, { align: 'center' });
        doc.setFontSize(8);
        doc.setTextColor(...gray);
        doc.setFont('helvetica', 'normal');
        doc.text(isEn ? s.label_en : s.label, x, y + 6, { align: 'center' });
      });
      y += 22;
    }

    // Footer on cover
    doc.setFontSize(8);
    doc.setTextColor(...gray);
    doc.text('aiforpresident.github.io', pageWidth / 2, 275, { align: 'center' });
    doc.text(
      isEn ? 'Generated by AI for educational and civic reflection purposes' : 'Generado por IA con fines educativos y de reflexión ciudadana',
      pageWidth / 2, 282, { align: 'center' }
    );
    doc.text(new Date().toLocaleDateString(), pageWidth / 2, 289, { align: 'center' });

    // === PAGE 2: AI PROPOSALS ===
    doc.addPage();
    y = 20;
    doc.setFillColor(...dark);
    doc.rect(0, 0, pageWidth, 297, 'F');

    y = this.addSectionTitle(doc, isEn ? 'AI President Proposals' : 'Propuestas del Presidente IA', y, blue, white);
    y += 5;

    proposals.forEach(p => {
      if (y > 260) {
        doc.addPage();
        doc.setFillColor(...dark);
        doc.rect(0, 0, pageWidth, 297, 'F');
        y = 20;
      }

      // Category box
      doc.setFillColor(22, 27, 34);
      doc.roundedRect(margin, y, contentWidth, 8, 2, 2, 'F');
      doc.setFontSize(11);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...blue);
      const pIcon = this.sanitizeIcon(p.icon || '');
      doc.text(`${pIcon}  ${isEn ? p.title_en : p.title}`, margin + 4, y + 5.5);
      y += 12;

      // Description
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...gray);
      const desc = isEn ? p.description_en : p.description;
      const lines = doc.splitTextToSize(desc, contentWidth - 8);
      doc.text(lines, margin + 4, y);
      y += lines.length * 4.5 + 8;
    });

    // === PAGE 3: CANDIDATE COMPARISON (only top candidates with poll data) ===
    if (candidates && candidates.length > 0) {
    // Filter to candidates that have poll_pct (top candidates) + Presidente IA
    const topCandidates = candidates.filter(c => c.poll_pct > 0 || c.id === 'ia');
    // If no poll data, take first 10
    const displayCandidates = topCandidates.length > 2 ? topCandidates : candidates.slice(0, 10);
    // Limit to max 10 for readability
    const tableCandidates = displayCandidates.slice(0, 10);

    doc.addPage();
    doc.setFillColor(...dark);
    doc.rect(0, 0, pageWidth, 297, 'F');
    y = 20;

    y = this.addSectionTitle(doc, isEn ? 'Candidate Comparison (Top Candidates)' : 'Comparación de Candidatos (Principales)', y, blue, white);
    y += 5;

    const dims = ['education', 'security', 'economy', 'health', 'environment', 'corruption', 'technology', 'social'];
    const dimLabels = dims.map(d => I18n.t(`dimensions.${d}`));

    // Calculate column widths: first column wider for dimension labels
    const labelColW = 28;
    const dataColW = (contentWidth - labelColW) / tableCandidates.length;

    // Table header
    doc.setFillColor(22, 27, 34);
    doc.rect(margin, y, contentWidth, 10, 'F');
    doc.setFontSize(7);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...gray);
    doc.text(isEn ? 'Dimension' : 'Dimension', margin + 2, y + 6);
    tableCandidates.forEach((c, i) => {
      const hex = c.color;
      const r = parseInt(hex.slice(1, 3), 16);
      const g = parseInt(hex.slice(3, 5), 16);
      const b = parseInt(hex.slice(5, 7), 16);
      doc.setTextColor(r, g, b);
      // Use last name only for space
      const parts = c.name.split(' ');
      const shortName = parts.length > 1 ? parts[parts.length - 1] : c.name;
      const name = shortName.length > 10 ? shortName.substring(0, 9) + '.' : shortName;
      const x = margin + labelColW + dataColW * i + dataColW / 2;
      doc.text(name, x, y + 6, { align: 'center' });
    });
    y += 12;

    // Table rows
    dims.forEach((d, di) => {
      if (y > 275) {
        doc.addPage();
        doc.setFillColor(...dark);
        doc.rect(0, 0, pageWidth, 297, 'F');
        y = 20;
      }

      if (di % 2 === 0) {
        doc.setFillColor(28, 33, 40);
        doc.rect(margin, y - 1, contentWidth, 8, 'F');
      }

      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...white);
      doc.text(dimLabels[di], margin + 2, y + 5);

      tableCandidates.forEach((c, i) => {
        const score = c.scores[d];
        if (score >= 7) doc.setTextColor(...green);
        else if (score >= 5) doc.setTextColor(...gold);
        else doc.setTextColor(...red);
        doc.setFont('helvetica', 'bold');
        const x = margin + labelColW + dataColW * i + dataColW / 2;
        doc.text(`${score}/10`, x, y + 5, { align: 'center' });
      });
      y += 8;
    });

    // Candidate details (only top candidates)
    y += 10;
    tableCandidates.forEach(c => {
      if (y > 250) {
        doc.addPage();
        doc.setFillColor(...dark);
        doc.rect(0, 0, pageWidth, 297, 'F');
        y = 20;
      }

      const hex = c.color;
      const r = parseInt(hex.slice(1, 3), 16);
      const g = parseInt(hex.slice(3, 5), 16);
      const b = parseInt(hex.slice(5, 7), 16);

      doc.setDrawColor(r, g, b);
      doc.setLineWidth(0.5);
      doc.line(margin, y, margin + contentWidth, y);
      y += 5;

      doc.setFontSize(10);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(r, g, b);
      doc.text(c.name, margin, y);
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...gray);
      doc.text(c.party, margin + doc.getTextWidth(c.name) + 5, y);
      if (c.poll_pct) {
        doc.setTextColor(...blue);
        doc.text(`${c.poll_pct}%`, margin + contentWidth - 10, y, { align: 'right' });
      }
      y += 6;

      doc.setFontSize(8);
      c.key_proposals.forEach(p => {
        doc.setTextColor(...white);
        const propLines = doc.splitTextToSize(`- ${p}`, contentWidth - 8);
        doc.text(propLines, margin + 4, y);
        y += propLines.length * 4;
      });
      y += 5;
    });
    } // end if candidates

    // === PAGE 4: KEY ISSUES ===
    doc.addPage();
    doc.setFillColor(...dark);
    doc.rect(0, 0, pageWidth, 297, 'F');
    y = 20;

    y = this.addSectionTitle(doc, isEn ? 'Key Issues' : 'Problemas Clave', y, blue, white);
    y += 5;

    const sorted = [...issues].sort((a, b) => b.severity - a.severity);

    sorted.forEach(issue => {
      if (y > 260) {
        doc.addPage();
        doc.setFillColor(...dark);
        doc.rect(0, 0, pageWidth, 297, 'F');
        y = 20;
      }

      // Severity bar
      const barColor = issue.severity >= 8 ? red : issue.severity >= 6 ? gold : green;
      doc.setFillColor(22, 27, 34);
      doc.roundedRect(margin, y, contentWidth, 4, 1, 1, 'F');
      doc.setFillColor(...barColor);
      doc.roundedRect(margin, y, contentWidth * (issue.severity / 10), 4, 1, 1, 'F');
      y += 7;

      doc.setFontSize(10);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...white);
      const issIcon = this.sanitizeIcon(issue.icon || '');
      doc.text(`${issIcon}  ${isEn ? issue.name_en : issue.name}`, margin, y);
      doc.setTextColor(...barColor);
      doc.text(`${issue.severity}/10`, margin + contentWidth - 10, y);
      y += 5;

      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...gray);
      const descLines = doc.splitTextToSize(isEn ? issue.description_en : issue.description, contentWidth - 4);
      doc.text(descLines, margin + 2, y);
      y += descLines.length * 4 + 8;
    });

    // Add page numbers to all pages
    const totalPages = doc.internal.getNumberOfPages();
    for (let i = 2; i <= totalPages; i++) {
      doc.setPage(i);
      doc.setFontSize(7);
      doc.setTextColor(...gray);
      doc.text(`AI for President — ${countryName}`, margin, 290);
      doc.text(`${i}/${totalPages}`, pageWidth - margin, 290, { align: 'right' });
    }

    // Save
    const safeName = countryName.replace(/\s+/g, '-');
    const filename = isEn ? `AI-President-${safeName}-Proposals.pdf` : `Presidente-IA-${safeName}-Propuestas.pdf`;
    doc.save(filename);
  },

  addSectionTitle(doc, text, y, color, textColor) {
    doc.setDrawColor(...color);
    doc.setLineWidth(0.8);
    doc.line(20, y + 8, 190, y + 8);
    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...textColor);
    doc.text(text, 20, y + 5);
    return y + 14;
  },

  formatStatValue(s) {
    const v = s.value;
    switch (s.format) {
      case 'number': return v.toLocaleString();
      case 'currency': return `${s.prefix || ''}${v.toLocaleString()}`;
      case 'percent': return `${v}%`;
      case 'years': return `${v}`;
      case 'decimal': return v.toFixed(2);
      default: return String(v);
    }
  }
};
